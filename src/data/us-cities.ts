const LABEL_MAP: Map<string, UsCity> = new Map(
  US_CITIES.map((c) => [labelOf(c).toLowerCase(), c])
);

export function labelOf(c: UsCity): string {
  return `${c.city}, ${c.state}`;
}

export function findCityByLabel(label: string): UsCity | undefined {
  return LABEL_MAP.get(label.trim().toLowerCase());
}

export function searchCities(query: string, limit = 8): UsCity[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const startsWith: UsCity[] = [];
  const contains: UsCity[] = [];
  for (const c of US_CITIES) {
    const label = labelOf(c).toLowerCase();
    if (label.startsWith(q)) startsWith.push(c);
    else if (label.includes(q)) contains.push(c);
    if (startsWith.length >= limit) break;
  }
  return [...startsWith, ...contains].slice(0, limit);
}
